"""Smooth reference-trajectory generator.

Instead of handing the controller a step target (jump straight to the
goal, which is what ik_gravity_panel.py does), integrate a critically-
damped second-order reference-model ODE each control tick to produce a
smoothly evolving intermediate target -- position, velocity, and
acceleration -- that gradually approaches the goal:

    qddot_ref = omega_n^2 * (q_goal - q_ref) - 2*zeta*omega_n*qdot_ref

The controller then tracks this moving reference (rigid_body_dynamics.py's
target_velocity/target_accel params) instead of reacting to a step input.
This is what actually removes the sharp initial-transient/high-jerk motion
a step target produces -- the "PD controls" (the target fed into Kp*e +
Kd*edot) are now dynamic, continuously changing, generated by numerically
solving this ODE, rather than a single fixed number set once at t=0.

This trajectory is virtual -- it costs nothing physically, it's just
numbers evolving in Python each step, decoupled from the arm's own
mass-matrix dynamics in rigid_body_dynamics.py.
"""
import numpy as np


class ReferenceTrajectory:
    def __init__(self, n=4):
        self.n = n
        self.q_ref = np.zeros(n)
        self.qdot_ref = np.zeros(n)

    def reset(self, start):
        self.q_ref = np.array(start, dtype=float)
        self.qdot_ref = np.zeros(self.n)

    def step(self, dt, goal, smoothing_time, zeta=1.0):
        """Advance the reference by dt toward goal. smoothing_time (s) is
        roughly how long the reference takes to settle near the goal
        (~4/omega_n for critically damped) -- smaller is snappier, larger
        is smoother/slower. zeta=1 is critically damped (no overshoot in
        the reference itself); <1 underdamped, >1 overdamped.
        Returns (q_ref, qdot_ref, qddot_ref), each a length-n array."""
        omega_n = 4.0 / max(smoothing_time, 1e-3)
        goal = np.asarray(goal, dtype=float)

        qddot_ref = (omega_n ** 2) * (goal - self.q_ref) - 2 * zeta * omega_n * self.qdot_ref
        self.qdot_ref = self.qdot_ref + qddot_ref * dt
        self.q_ref = self.q_ref + self.qdot_ref * dt

        return self.q_ref.copy(), self.qdot_ref.copy(), qddot_ref
