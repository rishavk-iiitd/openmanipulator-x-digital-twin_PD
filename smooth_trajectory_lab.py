"""Smooth Trajectory PD Lab -- a copy of ik_gravity_lab.py where the PD
target is no longer a fixed step input.

Stage 1: type a target end-effector XYZ (mm); numerical inverse kinematics
(om_python/inverse_kinematics.py) finds joint angles that reach it.
Stage 2: om_python/trajectory.py integrates a critically-damped 2nd-order
reference ODE every control tick, producing a smoothly evolving
intermediate target (position/velocity/acceleration) that gradually
approaches the IK solution instead of jumping straight there -- the "PD
controls" are dynamic, continuously changing, generated by numerically
solving that ODE.
Stage 3: the same computed-torque controller as ik_gravity_lab.py -- mass
matrix M(q), Coriolis C(q,qdot), gravity G(q) -- tracks that moving
reference, driving either the simulated "virtual robot" or the real arm
(same firmware/torque_link.py as pd_lab.py), visualized live in the same
3D viewer as the other programs.
"""
import threading

from om_python.renderer import ManipulatorView
from om_python.smooth_trajectory_panel import SmoothTrajectoryPanel
from om_python.state import SharedState


def main():
    state = SharedState()

    view = ManipulatorView(state)
    view_thread = threading.Thread(target=view.run, daemon=True)
    view_thread.start()

    panel = SmoothTrajectoryPanel(state)
    panel.run()  # blocks on the main thread until the panel window closes


if __name__ == "__main__":
    main()
